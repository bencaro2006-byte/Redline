// Embeds the SHA-256 of every bundled PowerShell script into the main bundle so the packaged
// app refuses to run a modified script. Runs automatically as part of `npm run build`.
// Usage: node scripts/hash-scripts.mjs
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const scripts = join(root, 'resources', 'scripts')
const output = join(root, 'src', 'main', 'ps', 'scriptHashes.ts')

const entries = readdirSync(scripts)
  .filter((name) => name.toLowerCase().endsWith('.ps1'))
  .sort()
  .map((name) => [name, createHash('sha256').update(readFileSync(join(scripts, name))).digest('hex')])

const body = entries.map(([name, hash]) => `  '${name}': '${hash}',`).join('\n')
writeFileSync(
  output,
  `// GENERATED by scripts/hash-scripts.mjs (runs in \`npm run build\`). Do not edit by hand.\n` +
    `// SHA-256 of each bundled PowerShell script, checked before every run in the packaged app.\n` +
    `export const SCRIPT_SHA256: Readonly<Record<string, string>> = {\n${body}\n}\n`,
  'utf8',
)
process.stdout.write(`scriptHashes.ts: ${entries.length} scripts\n`)
